#!/usr/bin/env python3
"""Build data/products-2020-05.json: satellite products on the app grid for the fishing-zone and climate views.

- Sea-surface temperature from OSTIA (Copernicus Marine SST_GLO_SST_L4_REP_OBSERVATIONS_010_011, 0.05 deg daily
  reprocessed analysis) on the 8 analysis days: each 0.5 deg cell the mean of the native pixels inside it.
- SST front strength on the same days: the gradient of the 0.05 deg field (central differences, deg C per km), and in
  each cell the 90th percentile of the pixel gradients, so a narrow front inside a cell still shows.
- The 1991-2020 climatology of the same calendar days (one day a year, 30 years), and every year's mean over those
  8 days in a Bay of Bengal box and an Arabian Sea box, 1982-2025, for the anomaly map and the long series.
- Surface chlorophyll-a from Copernicus-GlobColour (OCEANCOLOUR_GLO_BGC_L4_MY_009_104, gap-free 4 km daily
  multi-sensor) on the 8 days: each cell the geometric mean of its pixels (chlorophyll is log-normal).

The native NetCDF-4 files are read in HTTPS byte ranges by nc4.py, only the parts over the map, through
build_snapshot.py's cached Fetcher. Without --fetch nothing is downloaded.

    python data-pipeline/build_products.py [--fetch] [--cache DIR] [--out FILE] [--check]
"""
import argparse, base64, os, sys, urllib.parse, warnings
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime, timezone

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import build_snapshot as B                      # noqa: E402  (fetcher, byte ranges, grid, cell helpers, writer)

ROOT = 'https://s3.waw3-1.cloudferro.com'
OSTIA = (f'{ROOT}/mdl-native-06', 'native/SST_GLO_SST_L4_REP_OBSERVATIONS_010_011/METOFFICE-GLO-SST-L4-REP-OBS-SST_202003',
         '{t:%Y%m%d}120000-UKMO-L4_GHRSST-SSTfnd-OSTIA-GLOB_REP-v02.0-fv02.0.nc')
GLOBCOLOUR = (f'{ROOT}/mdl-native-16', 'native/OCEANCOLOUR_GLO_BGC_L4_MY_009_104/'
              'cmems_obs-oc_glo_bgc-plankton_my_l4-gapfree-multi-4km_P1D_202603',
              '{t:%Y%m%d}_cmems_obs-oc_glo_bgc-plankton_my_l4-gapfree-multi-4km_P1D.nc')
YEARS = list(range(1982, 2026))                 # OSTIA starts in October 1981
CLIM = (1991, 2020)                             # the WMO normal period
CASE_YEAR = 2020
BOXES = {'bay': {'lat': [8.0, 21.0], 'lon': [80.5, 92.0]}, 'arabian': {'lat': [8.0, 22.0], 'lon': [61.0, 77.0]}}
QUANT = {'sst': (15.0, 0.001), 'clim': (15.0, 0.001), 'chl': (0.0, 0.001), 'front': (0.0, 0.00002)}
MISSING = -32768
MIN_SHARE = 0.25                                # a front or chlorophyll cell needs a quarter of its pixels
KM_PER_DEG = 111.195
SCHEMA = 1
CITATIONS = [
    {'id': 'ostia', 'doi': '10.48670/moi-00168',
     'text': 'E.U. Copernicus Marine Service Information: Global Ocean OSTIA Sea Surface Temperature and Sea Ice '
             'Reprocessed (SST_GLO_SST_L4_REP_OBSERVATIONS_010_011), doi:10.48670/moi-00168. Good, S. et al. (2020), '
             'The current configuration of the OSTIA system for operational production of foundation sea surface '
             'temperature and ice concentration analyses, Remote Sens. 12, 720.'},
    {'id': 'globcolour', 'doi': '10.48670/moi-00281',
     'text': 'E.U. Copernicus Marine Service Information: Global Ocean Colour (Copernicus-GlobColour), Bio-Geo-Chemical, '
             'L4 from Satellite Observations (OCEANCOLOUR_GLO_BGC_L4_MY_009_104), gap-free daily 4 km chlorophyll-a, '
             'doi:10.48670/moi-00281. Generated by ACRI-ST.'},
]


def days(year):
    """The 8 analysis days (month and day of the snapshot times) in a given year, at 12:00 UTC."""
    return [datetime(year, t.month, t.day, 12, tzinfo=timezone.utc) for t in B.SNAPS]


def listing(F, src, year, month):
    root, prefix, _ = src
    p = urllib.parse.quote(f'{prefix}/{year:04d}/{month:02d}/', safe='/')
    tag = 'ostia' if src is OSTIA else 'globcolour'
    return F.get(f'{root}?list-type=2&prefix={p}', f'{tag}/listing-{year:04d}-{month:02d}.xml', B.parse_s3_listing)


def open_day(F, src, t, files):
    """The native file of day t as an nc4 File read in byte ranges."""
    import nc4
    root, prefix, pattern = src
    key = f'{prefix}/{t:%Y/%m}/' + pattern.format(t=t)
    B.require(key in files, f'no native file {key.rsplit("/", 1)[1]}')
    tag = 'ostia' if src is OSTIA else 'globcolour'
    return nc4.open_source(B.RangeSource(F, f'{root}/{key}', f'{tag}/' + key.rsplit('/', 1)[1], files[key]),
                           max_bytes=1 << 28)


def box_of(lat, lon, pad=0.35):
    """Index slices of a 1-D lat (either order) and lon axis that hold the map with a margin."""
    ii = np.where((lat >= B.LAT0 - pad) & (lat <= B.LAT1 + pad))[0]
    jj = np.where((lon >= B.LON0 - pad) & (lon <= B.LON1 + pad))[0]
    return slice(ii[0], ii[-1] + 1), slice(jj[0], jj[-1] + 1)


def gradient_km(T, lat, lon):
    """|grad T| (per km) on a regular lat/lon grid, central differences; NaN on the edge and next to a gap."""
    ky = KM_PER_DEG * abs(lat[1] - lat[0])
    kx = KM_PER_DEG * abs(lon[1] - lon[0]) * np.cos(np.radians(lat))
    g = np.full(T.shape, np.nan)
    gy = (T[2:, 1:-1] - T[:-2, 1:-1]) / (2 * ky)
    gx = (T[1:-1, 2:] - T[1:-1, :-2]) / (2 * kx[1:-1, None])
    g[1:-1, 1:-1] = np.hypot(gx, gy)
    return g


def cell_stat(a, rows, cols, fn):
    """fn over the finite samples of each cell, NaN where under MIN_SHARE of them are finite."""
    out = np.full((len(rows), len(cols)), np.nan)
    for i, r in enumerate(rows):
        for j, c in enumerate(cols):
            blk = a[np.ix_(r, c)]
            ok = np.isfinite(blk)
            if ok.sum() >= MIN_SHARE * blk.size and ok.any():
                out[i, j] = fn(blk[ok])
    return out


def geometric_mean(v):
    v = v[v > 0]
    return float(10 ** np.mean(np.log10(v))) if v.size else np.nan


def box_mean(field, box):
    """Mean of the finite cells of a [lat][lon] app-grid field inside a box (inclusive)."""
    la = (B.LATS >= box['lat'][0]) & (B.LATS <= box['lat'][1])
    lo = (B.LONS >= box['lon'][0]) & (B.LONS <= box['lon'][1])
    sub = field[np.ix_(la, lo)]
    return float(np.nanmean(sub)) if np.isfinite(sub).any() else np.nan


def ostia_day(F, t, files, fronts=False):
    """OSTIA on day t on the app grid (deg C, cell means), and with fronts the cell front strength (deg C/km)."""
    f = open_day(F, OSTIA, t, files)
    lat, lon = f.vars['lat'].read(), f.vars['lon'].read()
    ys, xs = box_of(lat, lon)
    v = f.vars['analysed_sst']
    a = np.asarray(v.read((0, ys, xs)), 'f8') - 273.15            # nc4 applies scale_factor, add_offset and fill
    lat, lon = lat[ys], lon[xs]
    rows, cols = B.cell_members(lat, B.LATS), B.cell_members(lon, B.LONS)
    sst = B.cell_mean(a, rows, cols)
    front = cell_stat(gradient_km(a, lat, lon), rows, cols, lambda x: float(np.percentile(x, 90))) if fronts else None
    return sst, front


def chl_day(F, t, files):
    f = open_day(F, GLOBCOLOUR, t, files)
    lat, lon = f.vars['lat'].read(), f.vars['lon'].read()
    ys, xs = box_of(lat, lon)
    a = np.asarray(f.vars['CHL'].read((0, ys, xs)), 'f8')
    return cell_stat(a, B.cell_members(lat[ys], B.LATS), B.cell_members(lon[xs], B.LONS), geometric_mean)


def pack(a, key):
    off, sc = QUANT[key]
    q = np.round((np.asarray(a, 'f8') - off) / sc)
    q = np.where(np.isfinite(q), np.clip(q, -32767, 32767), MISSING).astype('<i2')
    return base64.b64encode(q.tobytes()).decode('ascii')


def build(F, log=print, workers=8):
    files = {}
    for y in YEARS:
        files.update(listing(F, OSTIA, y, 5))
    oc_files = listing(F, GLOBCOLOUR, CASE_YEAR, 5)
    jobs = [(y, d) for y in YEARS for d in range(len(B.SNAPS))]
    with ThreadPoolExecutor(workers) as ex:
        got = dict(zip(jobs, ex.map(lambda j: ostia_day(F, days(j[0])[j[1]], files, fronts=j[0] == CASE_YEAR), jobs)))
        chl = list(ex.map(lambda t: chl_day(F, t, oc_files), days(CASE_YEAR)))
    log(f'  OSTIA: {len(jobs)} days read ({len(YEARS)} years x {len(B.SNAPS)}); GlobColour: {len(chl)} days')
    sst = np.stack([got[(CASE_YEAR, d)][0] for d in range(len(B.SNAPS))])
    front = np.stack([got[(CASE_YEAR, d)][1] for d in range(len(B.SNAPS))])
    clim_years = [y for y in YEARS if CLIM[0] <= y <= CLIM[1]]
    with warnings.catch_warnings():                 # land cells have no value in any year: NaN, said once here
        warnings.simplefilter('ignore', RuntimeWarning)
        clim = np.stack([np.nanmean([got[(y, d)][0] for y in clim_years], axis=0) for d in range(len(B.SNAPS))])
    series = {name: [round(float(np.mean([box_mean(got[(y, d)][0], box) for d in range(len(B.SNAPS))])), 3)
                     for y in YEARS] for name, box in BOXES.items()}
    B.require(np.isfinite(sst).mean() > 0.5 and np.isfinite(chl).mean() > 0.5, 'the satellite fields are mostly empty')
    B.require(len(clim_years) == 30, 'the climatology needs the 30 years 1991-2020')
    man, inputs = F.manifest(), {}
    for group in ('ostia', 'globcolour'):
        names = sorted(n for n in F.used if n.startswith(group + '/'))
        inputs[group] = {'files': len(names), 'sha256_of_hashes': B.sha256(''.join(F.used[n] for n in names).encode()),
                         'accessed': max((man.get(n, {}).get('fetched', '')[:10] for n in names), default='')}
    return {
        'schema': SCHEMA,
        'meta': {
            'title': 'Satellite SST, fronts, climatology and chlorophyll, Cyclone Amphan window, May 2020',
            'times': [t.strftime('%Y-%m-%dT%H:%MZ') for t in B.SNAPS],
            'lat0': B.LAT0, 'lon0': B.LON0, 'step': B.STEP, 'nlat': len(B.LATS), 'nlon': len(B.LONS),
            'quant': {k: list(v) for k, v in QUANT.items()}, 'missing': MISSING,
            'units': {'sst': 'degree_Celsius', 'clim': 'degree_Celsius', 'chl': 'mg m-3', 'front': 'degree_Celsius per km'},
            'climatology': {'years': list(CLIM), 'days': 'the same calendar days, one a year'},
            'sources': {
                'sst': 'OSTIA reprocessed L4 foundation SST, 0.05 deg daily (Copernicus Marine '
                       'SST_GLO_SST_L4_REP_OBSERVATIONS_010_011); each 0.5 deg cell the mean of the pixels inside it.',
                'front': 'The gradient of the 0.05 deg OSTIA field by central differences (deg C per km); each cell the '
                         '90th percentile of its pixel gradients, where at least a quarter of them are defined.',
                'clim': 'The mean of the same calendar day over 1991-2020 (30 OSTIA days for each analysis day).',
                'chl': 'Copernicus-GlobColour gap-free L4 daily multi-sensor chlorophyll-a, 4 km '
                       '(OCEANCOLOUR_GLO_BGC_L4_MY_009_104); each cell the geometric mean of its pixels, where at least '
                       'a quarter are defined. Gap-free means clouds are filled by interpolation.',
                'series': 'Each year 1982-2025, the mean OSTIA SST over the 8 analysis days in each box.'},
            'citations': CITATIONS,
            'provenance': {'ostia': {'url': OSTIA[0], 'prefix': OSTIA[1], 'years': [YEARS[0], YEARS[-1]],
                                     'read': 'NetCDF-4 chunks in HTTPS byte ranges by data-pipeline/nc4.py'},
                           'globcolour': {'url': GLOBCOLOUR[0], 'prefix': GLOBCOLOUR[1], 'year': CASE_YEAR}},
            'inputs': inputs,
        },
        'sst': pack(sst, 'sst'), 'front': pack(front, 'front'), 'clim': pack(clim, 'clim'), 'chl': pack(np.stack(chl), 'chl'),
        'series': {'years': YEARS, 'boxes': BOXES, **series},
    }


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--cache', default=os.environ.get('OCEANLENS_CACHE') or os.path.join(HERE, 'cache'))
    ap.add_argument('--out', default=os.path.join(HERE, '..', 'data', 'products-2020-05.json'))
    ap.add_argument('--fetch', action='store_true', help='download what the cache lacks')
    ap.add_argument('--ca-bundle', default=os.environ.get('OCEANLENS_CA_BUNDLE'))
    ap.add_argument('--check', action='store_true', help='rebuild and compare with --out instead of writing it')
    a = ap.parse_args(argv)
    F = B.Fetcher(a.cache, fetch=a.fetch, cafile=a.ca_bundle)
    try:
        text = B.serialise(build(F))
    except B.CacheMiss as e:
        print(f'missing from the cache: {e} (run with --fetch)', file=sys.stderr)
        return 2
    if a.check:
        with open(a.out, 'rb') as f:
            same = f.read() == text
        print(f"check {'ok' if same else 'failed'}: {a.out}")
        return 0 if same else 1
    B.write_atomic(a.out, text)
    print(f'wrote {a.out} ({len(text) / 1000:.0f} kB, {F.downloaded / 1e6:.0f} MB downloaded)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
