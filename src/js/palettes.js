const PALETTES = {
  thermal: [[0,[27,26,110]],[0.28,[27,120,170]],[0.55,[70,190,120]],[0.78,[235,210,60]],[1,[200,45,35]]],
  haline:  [[0,[10,28,66]],[0.4,[18,92,112]],[0.7,[64,164,140]],[1,[196,232,182]]],
  speed:   [[0,[28,10,64]],[0.35,[110,20,140]],[0.65,[224,60,120]],[1,[255,224,80]]],
  heat:    [[0,[22,18,44]],[0.3,[104,32,96]],[0.6,[214,78,52]],[0.85,[248,176,62]],[1,[255,244,204]]],
  // isosurface depth: pale = shallow, deep navy = deep (deliberately unlike the value palettes)
  depth:   [[0,[222,246,236]],[0.3,[112,204,190]],[0.65,[42,122,170]],[1,[32,42,112]]]
};
function paletteColor(name, t){
  t = Math.min(1,Math.max(0,t));
  const stops = PALETTES[name];
  for(let i=0;i<stops.length-1;i++){
    const [p0,c0]=stops[i], [p1,c1]=stops[i+1];
    if(t>=p0 && t<=p1){
      const f=(t-p0)/(p1-p0);
      return [lerp(c0[0],c1[0],f)/255, lerp(c0[1],c1[1],f)/255, lerp(c0[2],c1[2],f)/255];
    }
  }
  return [1,1,1];
}
